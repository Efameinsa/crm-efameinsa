// ============================================================
// CRM EFAMEINSA · Respaldo completo y portable
// ============================================================
// El respaldo de siempre (scripts/backup-datos.mjs) guarda las FILAS de las
// tablas públicas y nada más. Alcanza para recuperar un dato borrado, pero no
// para llevarse el CRM a otra parte: deja fuera el esquema tal como está vivo
// hoy, los usuarios que inician sesión, los archivos adjuntos y las 152
// funciones que son, en la práctica, la mitad de las reglas del negocio.
//
// Este respaldo se lleva todo, y no necesita a Supabase para volver:
//
//   base/esquema/    el DDL leído del catálogo VIVO, no de las migraciones.
//                    Importa porque las funciones se parchan en caliente (ver
//                    crm-no-copiar-funciones-cotizacion): el .sql de una
//                    migración puede no ser lo que corre hoy.
//   base/datos/      las 52 tablas públicas en NDJSON, más los usuarios de
//                    auth y el inventario de storage.
//   archivos/        los adjuntos de verdad, bajados uno por uno.
//   codigo/          un git bundle —todo el historial y todas las ramas en un
//                    solo archivo— más lo que estaba sin commitear.
//
// Los secretos NO entran acá: van en un zip aparte, para que este respaldo se
// pueda entregar a un tercero sin regalar las llaves de producción.
//
// Uso:  node --env-file=.env.local scripts/respaldo-completo.mjs
// ============================================================

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync, createWriteStream, statSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Client } from "pg";

const RAIZ = join(dirname(fileURLToPath(import.meta.url)), "..");
const FECHA = new Date().toISOString().slice(0, 10);
const DESTINO = join(RAIZ, "backups", `respaldo-completo-${FECHA}`);

for (const v of ["DATABASE_URL", "NEXT_PUBLIC_SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY"]) {
  if (!process.env[v]) {
    console.error(`Falta ${v} en .env.local`);
    process.exit(1);
  }
}

const bd = new Client({ connectionString: process.env.DATABASE_URL, ssl: { rejectUnauthorized: false } });
const q = async (s, p = []) => (await bd.query(s, p)).rows;
const dir = (...p) => {
  const d = join(DESTINO, ...p);
  mkdirSync(d, { recursive: true });
  return d;
};
const kb = (n) => (n < 1048576 ? `${(n / 1024).toFixed(1)} KB` : `${(n / 1048576).toFixed(2)} MB`);

await bd.connect();
console.log(`Respaldo del ${FECHA} -> ${DESTINO}\n`);

// ── 1. EL ESQUEMA, LEÍDO DEL CATÁLOGO VIVO ──────────────────────────────
const dEsq = dir("base", "esquema");
const sql = (n, texto) => {
  writeFileSync(join(dEsq, n), texto, "utf8");
  console.log(`   esquema/${n}`);
};
console.log("1. Esquema vivo");

const ext = await q(`select extname, extversion from pg_extension where extname <> 'plpgsql' order by 1`);
sql("01-extensiones.sql", ext.map((e) => `create extension if not exists "${e.extname}";  -- ${e.extversion}`).join("\n") + "\n");

const enums = await q(`
  select t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) vals
    from pg_type t
    join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
   where n.nspname = 'public'
   group by t.typname order by t.typname`);
sql("02-enums.sql", enums.map((e) => `create type public.${e.typname} as enum (${e.vals});`).join("\n") + "\n");

const tablas = await q(`
  select c.relname tabla, c.relrowsecurity rls,
         string_agg(format('  %I %s%s%s%s', a.attname,
           format_type(a.atttypid, a.atttypmod),
           case a.attidentity when 'a' then ' generated always as identity'
                              when 'd' then ' generated by default as identity' else '' end,
           case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
           case when a.attnotnull then ' not null' else '' end),
           E',\n' order by a.attnum) columnas
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
   where n.nspname = 'public' and c.relkind = 'r'
   group by c.relname, c.relrowsecurity order by c.relname`);

const restricciones = await q(`
  select c.relname tabla, con.conname, pg_get_constraintdef(con.oid) def, con.contype
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public'
   order by con.contype, c.relname, con.conname`);

sql("03-tablas.sql",
  tablas.map((t) => {
    const propias = restricciones.filter((k) => k.tabla === t.tabla && k.contype !== "f");
    const cuerpo = propias.length
      ? `${t.columnas},\n${propias.map((k) => `  constraint ${k.conname} ${k.def}`).join(",\n")}`
      : t.columnas;
    return `create table public.${t.tabla} (\n${cuerpo}\n);`;
  }).join("\n\n") +
  "\n\n-- Llaves foráneas al final: las tablas se referencian entre sí.\n" +
  restricciones.filter((k) => k.contype === "f")
    .map((k) => `alter table public.${k.tabla} add constraint ${k.conname} ${k.def};`).join("\n") +
  "\n\n-- Row Level Security\n" +
  tablas.filter((t) => t.rls).map((t) => `alter table public.${t.tabla} enable row level security;`).join("\n") + "\n");

const indices = await q(`
  select indexdef from pg_indexes
   where schemaname = 'public' and indexname not in (select conname from pg_constraint)
   order by tablename, indexname`);
sql("04-indices.sql", indices.map((i) => i.indexdef + ";").join("\n") + "\n");

const vistas = await q(`
  select table_name v, pg_get_viewdef(('public.' || table_name)::regclass, true) def
    from information_schema.views where table_schema = 'public' order by 1`);
sql("05-vistas.sql", vistas.map((v) => `create or replace view public.${v.v} as\n${v.def}`).join("\n\n") + "\n");

// Solo las nuestras: pg_trgm y uuid-ossp se instalaron dentro de `public` y
// dejan ahí un centenar de funciones en C que no son código del CRM. Las trae
// de vuelta el `create extension` del paso 01; copiarlas rompía el ensayo de
// restauración con «permission denied for language c» (05-09).
const funciones = await q(`
  select p.proname, pg_get_functiondef(p.oid) def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
   order by p.proname`);
sql("06-funciones.sql",
  `-- ${funciones.length} funciones propias del CRM, tal como corren HOY en\n` +
  `-- producción (las de las extensiones las repone el paso 01).\n` +
  `-- Ojo: varias se parcharon en caliente sobre la definición viva, así que\n` +
  `-- esto manda sobre lo que digan los archivos de supabase/migrations.\n\n` +
  funciones.map((f) => f.def.trimEnd() + ";").join("\n\n") + "\n");

const triggers = await q(`
  select pg_get_triggerdef(t.oid) def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and not t.tgisinternal
   order by c.relname, t.tgname`);
sql("07-triggers.sql", triggers.map((t) => t.def + ";").join("\n") + "\n");

const pols = await q(`select * from pg_policies where schemaname = 'public' order by tablename, policyname`);
sql("08-politicas-rls.sql",
  `-- ${pols.length} políticas: acá vive quién ve qué. Es el corazón de los\n` +
  `-- permisos del CRM y lo primero que habría que traducir si se cambia de\n` +
  `-- arquitectura, porque hoy la seguridad NO está en el código de la app.\n\n` +
  pols.map((p) =>
    `create policy ${JSON.stringify(p.policyname)} on public.${p.tablename}\n` +
    `  as ${p.permissive} for ${p.cmd} to ${String(p.roles).replace(/[{}]/g, "")}` +
    (p.qual ? `\n  using (${p.qual})` : "") +
    (p.with_check ? `\n  with check (${p.with_check})` : "") + ";").join("\n\n") + "\n");

const permisos = await q(`
  select grantee, table_name, string_agg(privilege_type, ', ' order by privilege_type) permisos
    from information_schema.role_table_grants
   where table_schema = 'public'
   group by grantee, table_name order by grantee, table_name`);
sql("09-permisos.sql", permisos.map((g) => `grant ${g.permisos.toLowerCase()} on public.${g.table_name} to ${g.grantee};`).join("\n") + "\n");

const comentarios = await q(`
  select 'comment on table public.' || c.relname || ' is ' || quote_literal(d.description) || ';' linea
    from pg_description d
    join pg_class c on c.oid = d.objoid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and d.objsubid = 0 and c.relkind = 'r'
   union all
  select 'comment on column public.' || c.relname || '.' || a.attname || ' is ' || quote_literal(d.description) || ';'
    from pg_description d
    join pg_class c on c.oid = d.objoid
    join pg_attribute a on a.attrelid = c.oid and a.attnum = d.objsubid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and d.objsubid > 0`);
sql("10-comentarios.sql", comentarios.map((c) => c.linea).join("\n") + "\n");

// ── 2. LOS DATOS ────────────────────────────────────────────────────────
console.log("\n2. Datos");
const dDatos = dir("base", "datos");
const conteo = {};

// Por tandas, con un cursor del servidor. `select * from leads` de un tirón
// son 20 MB y el pooler de Supabase corta la conexión a medio camino (pasó el
// 05-09). Y todo va dentro de UNA transacción repeatable read: así las 52
// tablas son la misma foto del mismo instante, y no una colcha de retazos
// donde un cierre existe pero su venta todavía no.
const TANDA = 2000;

async function volcar(esquema, tabla, archivo = `${tabla}.ndjson`) {
  await bd.query(`declare c_volcado no scroll cursor for select * from "${esquema}"."${tabla}"`);
  const f = createWriteStream(join(dDatos, archivo), "utf8");
  let n = 0;
  for (;;) {
    const { rows } = await bd.query(`fetch ${TANDA} from c_volcado`);
    if (rows.length === 0) break;
    for (const r of rows) f.write(JSON.stringify(r) + "\n");
    n += rows.length;
  }
  await new Promise((ok) => f.end(ok));
  await bd.query("close c_volcado");
  conteo[`${esquema}.${tabla}`] = n;
  return n;
}

await bd.query("begin isolation level repeatable read");

const publicas = await q(`
  select table_name from information_schema.tables
   where table_schema = 'public' and table_type = 'BASE TABLE' order by table_name`);
let filas = 0;
for (const { table_name } of publicas) {
  const n = await volcar("public", table_name);
  filas += n;
  if (n > 1000) console.log(`   ${table_name}: ${n.toLocaleString("es-PE")} filas`);
}
console.log(`   ${publicas.length} tablas públicas · ${filas.toLocaleString("es-PE")} filas en total`);

// auth y storage viven fuera de `public`. Sin auth nadie inicia sesión en la
// copia: van las contraseñas cifradas (bcrypt), que es lo que permite que las
// cuentas sigan sirviendo. Cada una con su punto de retorno, porque un error
// dentro de la transacción se llevaría todo lo demás por delante.
for (const [esquema, t] of [["auth", "users"], ["auth", "identities"], ["storage", "buckets"], ["storage", "objects"]]) {
  await bd.query("savepoint sp_fuera");
  try {
    console.log(`   ${esquema}.${t}: ${await volcar(esquema, t, `${esquema}-${t}.ndjson`)}`);
  } catch (e) {
    await bd.query("rollback to savepoint sp_fuera");
    console.log(`   ${esquema}.${t}: no accesible (${e.message.slice(0, 60)})`);
  }
}

await bd.query("commit"); // se cierra la foto: de acá en adelante ya no importa el instante

// ── 3. LOS ARCHIVOS ─────────────────────────────────────────────────────
console.log("\n3. Archivos adjuntos");
const objetos = await q(`
  select b.name bucket, o.name ruta
    from storage.objects o join storage.buckets b on b.id = o.bucket_id order by 1, 2`);
const base = process.env.NEXT_PUBLIC_SUPABASE_URL.replace(/\/$/, "");
let bajados = 0;
let bytes = 0;
const fallidos = [];
for (const o of objetos) {
  const r = await fetch(`${base}/storage/v1/object/${o.bucket}/${encodeURI(o.ruta)}`, {
    headers: { Authorization: `Bearer ${process.env.SUPABASE_SERVICE_ROLE_KEY}` },
  });
  if (!r.ok) {
    fallidos.push(`${o.bucket}/${o.ruta} (${r.status})`);
    continue;
  }
  const buf = Buffer.from(await r.arrayBuffer());
  writeFileSync(join(dir("archivos", o.bucket, dirname(o.ruta)), o.ruta.split("/").pop()), buf);
  bajados++;
  bytes += buf.length;
}
console.log(`   ${bajados}/${objetos.length} archivos · ${kb(bytes)}`);
if (fallidos.length) console.log(`   no se pudieron bajar: ${fallidos.join(", ")}`);

// ── 4. EL CÓDIGO ────────────────────────────────────────────────────────
console.log("\n4. Código");
const dCod = dir("codigo");
const git = (...a) => execFileSync("git", a, { cwd: RAIZ, encoding: "utf8" }).trim();
const sha = git("rev-parse", "HEAD");
git("bundle", "create", join(dCod, "crm-efameinsa.bundle"), "--all");
console.log(`   git bundle (todo el historial) · ${kb(statSync(join(dCod, "crm-efameinsa.bundle")).size)}`);

// Lo que estaba sin commitear el día del respaldo: casi todo son scripts de
// diagnóstico `_...mjs`. Se copian tal cual, sin los datos pesados.
const sueltos = git("status", "--porcelain").split("\n").filter(Boolean)
  .map((l) => l.slice(3).replace(/^"|"$/g, ""))
  .filter((f) => !f.startsWith("scripts/data/") && !f.startsWith("backups/"));
const dTrabajo = dir("codigo", "sin-commitear");
let copiados = 0;
for (const f of sueltos) {
  const origen = join(RAIZ, f);
  if (!existsSync(origen) || statSync(origen).isDirectory()) continue;
  mkdirSync(join(dTrabajo, dirname(f)), { recursive: true });
  execFileSync("powershell.exe", ["-NoProfile", "-Command",
    `Copy-Item -LiteralPath '${origen}' -Destination '${join(dTrabajo, f)}' -Force`]);
  copiados++;
}
console.log(`   ${copiados} archivos sin commitear, copiados aparte`);

// ── 5. MANIFIESTO ───────────────────────────────────────────────────────
const [{ peso, v }] = await q(`select pg_size_pretty(pg_database_size(current_database())) peso, version() v`);
const migracion = (await q(`select archivo from _migraciones_aplicadas order by archivo desc limit 1`).catch(() => []))[0];
const manifiesto = {
  fecha: FECHA,
  generado_at: new Date().toISOString(),
  base: {
    peso,
    postgres: v.split(" on ")[0],
    migracion_mas_alta: migracion?.archivo ?? null,
    tablas: publicas.length,
    filas_publicas: filas,
    funciones: funciones.length,
    politicas_rls: pols.length,
    triggers: triggers.length,
    vistas: vistas.length,
    enums: enums.length,
    indices: indices.length,
    extensiones: ext.map((e) => e.extname),
  },
  archivos: { objetos: objetos.length, bajados, bytes, fallidos },
  codigo: { commit: sha, rama: git("rev-parse", "--abbrev-ref", "HEAD"), sin_commitear: copiados },
  conteo_por_tabla: conteo,
  no_incluido: [
    "scripts/data/fichas-v/ (205 MB; se regenera desde V: con los pasos fichas-v-01 a 12)",
    "node_modules/ y .next/ (se reconstruyen con npm install && npm run build)",
    ".env.local (va en el zip de secretos, aparte)",
  ],
};
writeFileSync(join(DESTINO, "manifiesto.json"), JSON.stringify(manifiesto, null, 2), "utf8");
await bd.end();
console.log("\n5. Manifiesto escrito");
console.log(JSON.stringify(manifiesto.base, null, 2));
